const assert = require('node:assert/strict');
const { releaseNotes } = require('../scripts/release-notes.cjs');
const changelog = '# Changelog\n\n## 1.0.1\n\n### Fixes\n\n- Fixed the download.\n\n## 1.0.0\n\n- First release.\n';
const notes = releaseNotes(changelog, '1.0.1');
assert.ok(notes.includes('Fixed the download.'));
assert.ok(!notes.includes('First release.'));
assert.ok(notes.includes('/compare/v1.0.0...v1.0.1'));
assert.throws(() => releaseNotes(changelog, '1.0.2'), /has no entry/);
assert.throws(() => releaseNotes('## 1.0.1\n', '1.0.1'), /missing/);
assert.throws(() => releaseNotes('## 1.0.1 (unreleased)\n- Test\n', '1.0.1'), /unreleased/);
assert.throws(() => releaseNotes(changelog, '../bad'), /Invalid/);
console.log('Release changelog extraction and missing-notes guards passed.');
