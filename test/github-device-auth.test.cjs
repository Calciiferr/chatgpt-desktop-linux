const assert = require('node:assert/strict');
const { GitHubDeviceAuth, GITHUB_CLIENT_ID, GitHubLoginExpiredError } = require('../dist/github-device-auth.js');
const original = global.fetch;
(async () => {
  let stored = null;
  let queue = [], requests = [], delays = [];
  global.fetch = async (url, options) => {
    requests.push({ url, fields: Object.fromEntries(options.body) });
    assert.equal(options.body.get('client_id'), GITHUB_CLIENT_ID);
    assert.equal(options.body.has('client_secret'), false);
    assert.equal(options.body.has('scope'), false, 'no broad OAuth repo scope');
    if (options.signal.aborted) throw new Error('cancelled');
    assert.ok(queue.length, 'no unexpected poll');
    return new Response(JSON.stringify(queue.shift()));
  };
  const device = { device_code: 'private-device-code', user_code: 'ABCD-1234', verification_uri: 'https://github.com/login/device', expires_in: 900, interval: 5 };
  const tokens = { access_token: 'test-access', refresh_token: 'test-refresh', expires_in: 28800, refresh_token_expires_in: 15897600 };
  const auth = new GitHubDeviceAuth(() => stored, value => { stored = value; }, async ms => { delays.push(ms); });
  queue = [device, { error: 'authorization_pending' }, { error: 'slow_down' }, tokens];
  const publicDevice = await auth.start();
  assert.equal(publicDevice.code, 'ABCD-1234');
  assert.equal(publicDevice.deviceCode, undefined, 'device secret stays in main process');
  await auth.complete();
  assert.deepEqual(delays, [5000, 5000, 10000]);
  assert.equal(await auth.token(), 'test-access');
  stored.expiresAt = Date.now() - 1;
  queue = [{ ...tokens, access_token: 'renewed', refresh_token: 'rotated' }];
  assert.deepEqual(await Promise.all([auth.token(), auth.token()]), ['renewed', 'renewed']);
  assert.equal(stored.refreshToken, 'rotated');
  assert.equal(requests.filter(r => r.fields.grant_type === 'refresh_token').length, 1);
  queue = [device, { error: 'access_denied' }];
  await auth.start();
  await assert.rejects(() => auth.complete(), /refusée/);
  assert.equal(stored.accessToken, 'renewed', 'denied relogin does not overwrite existing session');
  queue = [device];
  await auth.start();
  auth.cancel();
  await assert.rejects(() => auth.complete(), /Démarrez/);
  queue = [{ ...device, verification_uri: 'https://example.com' }];
  await assert.rejects(() => auth.start(), /Impossible/);
  const authFetch = global.fetch;
  global.fetch = async (url, options) => {
    assert.equal(url, 'https://api.github.com/user');
    assert.equal(options.headers.Authorization, 'Bearer renewed');
    return new Response(JSON.stringify({ login: 'test-user' }));
  };
  assert.equal(await auth.verify(), 'test-user');
  global.fetch = async () => new Response('', { status: 401 });
  await assert.rejects(() => auth.verify(), GitHubLoginExpiredError);
  global.fetch = async () => new Response('', { status: 503 });
  await assert.rejects(() => auth.verify(), /Impossible de vérifier/);
  assert.ok(stored, 'network failure preserves local login');
  global.fetch = authFetch;
  auth.disconnect();
  assert.equal(stored, null);
  await assert.rejects(() => auth.token(), /connecter/);
  console.log('GitHub device login and refresh tests passed.');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => { global.fetch = original; });
